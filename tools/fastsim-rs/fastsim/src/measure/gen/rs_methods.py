"""Writes measure/methods.rs from the Rust sim: the no-argument methods of the sim's state types,
as C# `Visibility.no_arg_method` found them by reflection (public instance methods, inherited
too, not void, every parameter optional), for `fastsim-rs measure visibility`.

    cd tools/fastsim-rs
    python fastsim/src/measure/gen/rs_methods.py sim/src fastsim/src/measure/methods.rs

The state types are `Visibility.state_types()`: SimState, RoomRuntime, then every hazard struct
(one with a `base: Base` field, or a parent hazard by value: `b: Bouncer`, `boss: Boss`,
`c: CoinPickup`) by name (ordinal). A type's methods:
- `pub fn name(self | &self | &mut self) -> T` with no other parameter in its inherent impls;
- those of its parent (the field above), up to `Base`, which has the `Hazard` trait's
  `fn name(&self) -> T` (band_top, band_bottom);
- not a Rust-only accessor: a method named like one of the type's fields (`def` for `def_`) or
  returning a reference to a hazard parent (`base()`, `base_mut()`, `boss_mut()`, `coin()`);
- plus EXTRA below.
Python 3 stdlib only. See README.md here for when to run it.
"""
import os
import re
import sys

ROOT = sys.argv[1]  # tools/fastsim-rs/sim/src
OUT = sys.argv[2]

# Methods the sim has with no argument needed that the Rust signatures cannot show:
EXTRA = {
    # Hazard.clone_deep(): Rust copies a hazard with Clone.
    'Base': ['clone_deep'],
    # Bouncer.straight_path(): Rust folds it into near_row (bouncer.rs, the subclasses' comments).
    'Bouncer': ['straight_path'],
    # inset(side = 0), spike_bonus(side = 0): an optional parameter; Rust takes `side`.
    'RoomRuntime': ['inset', 'spike_bonus'],
}

KEYWORDS = {'def', 'move', 'crate', 'type', 'loop', 'ref', 'box', 'mod', 'match', 'fn', 'in', 'use',
            'where', 'impl', 'self', 'super', 'dyn', 'gen'}


def strip(s):
    s = re.sub(r'"(\\.|[^"\\\n])*"', '""', s)
    s = re.sub(r'//[^\n]*', '', s)
    return s


def block(s, start):
    """The text inside the brace block whose `{` ends at `start`."""
    i, d = start, 1
    while d:
        d += (s[i] == '{') - (s[i] == '}')
        i += 1
    return s[start:i - 1]


FN = re.compile(r'^\s*(pub(?:\([^)]*\))?\s+)?(?:const\s+)?fn\s+(\w+)\s*(?:<[^>]*>)?'
                r'\(\s*(?:&\s*)?(?:mut\s+)?self\s*,?\s*\)\s*(?:->\s*([^{;]+?))?\s*[{;]', re.M)

structs = {}    # name -> [(field, type)]
inherent = {}   # name -> [(method, return type)]
trait_hazard = []
files = []
for d, _, fs in os.walk(ROOT):
    files += [os.path.join(d, f) for f in fs if f.endswith('.rs')]
for p in sorted(files):
    s = strip(open(p, encoding='utf-8').read())
    for m in re.finditer(r'^pub struct (\w+)\s*\{', s, re.M):
        fields = []
        for line in block(s, m.end()).split('\n'):
            fm = re.fullmatch(r'\s*(?:pub(?:\([^)]*\))?\s+)?(\w+)\s*:\s*(.+?),?\s*', line)
            if fm:
                fields.append((fm.group(1), fm.group(2)))
        structs[m.group(1)] = fields
    for m in re.finditer(r'^impl(?:<[^>]*>)?\s+(\w+)\s*\{', s, re.M):
        for fm in FN.finditer(block(s, m.end())):
            if fm.group(1) and fm.group(3):
                inherent.setdefault(m.group(1), []).append((fm.group(2), fm.group(3).strip()))
    m = re.search(r'^pub trait Hazard\b[^{]*\{', s, re.M)
    if m:
        trait_hazard += [(fm.group(2), fm.group(3).strip()) for fm in FN.finditer(block(s, m.end()))
                         if fm.group(3)]
inherent.setdefault('Base', []).extend(trait_hazard)


def parent(c):
    """The parent type of a hazard struct: Base, or the hazard struct it holds by value."""
    if c == 'Base' or c not in structs:
        return None
    for f, t in structs[c]:
        if t == 'Base' or (t in structs and parent(t) is not None):
            return t
    return None


def own_methods(c):
    names = {(f[:-1] if f.endswith('_') and f[:-1] in KEYWORDS else f) for f, _ in structs.get(c, [])}
    out = []
    for n, ret in inherent.get(c, []):
        r = re.fullmatch(r'&\s*(?:mut\s+)?(?:\w+::)*(\w+)', ret)
        if n in names or (r and (r.group(1) == 'Base' or parent(r.group(1)) is not None)):
            continue
        out.append(n)
    return out + EXTRA.get(c, [])


def all_methods(c):
    names = []
    while c is not None:
        names += own_methods(c)
        c = parent(c)
    return sorted(set(names))


hazards = sorted((c for c in structs if c != 'Base' and parent(c) is not None), key=lambda s: s.encode())
types = ['SimState', 'RoomRuntime'] + hazards
lines = [
    '//! GENERATED by gen/rs_methods.py from the Rust sim (tools/fastsim-rs/sim/src): the state types',
    '//! of C# `Visibility.state_types()` (SimState, RoomRuntime, then every hazard type by name) and',
    '//! the no-argument methods `Visibility.no_arg_method` finds on each by reflection (public,',
    '//! inherited too, not void, every parameter optional; Object\'s own left out).',
    '//! Regenerate when a sim type gains or loses such a method (see gen/README.md).',
    '',
    '/// (class, its no-argument methods in ordinal order), in `state_types()` order.',
    'pub const STATE_TYPES: &[(&str, &[&str])] = &[',
]
for t in types:
    ms = ', '.join('"%s"' % m for m in all_methods(t))
    lines.append('    ("%s", &[%s]),' % (t, ms))
lines.append('];')
open(OUT, 'w', newline='\n').write('\n'.join(lines) + '\n')
