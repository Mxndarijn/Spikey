"""The no-argument methods of the sim's state types, as C# `Visibility.no_arg_method` finds them
by reflection (public instance methods, inherited too, not void, every parameter optional),
written as measure/methods.rs for `fastsim-rs measure visibility`.

    cd tools/fastsim && python ../fastsim-rs/fastsim/src/measure/gen/cs_methods.py . ../fastsim-rs/fastsim/src/measure/methods.rs

The state types are C# `Visibility.state_types()`: SimState, RoomRuntime, then every
non-abstract subclass of Hazard by name (ordinal). Object's own methods (ToString,
GetHashCode, GetType) are left out: a painter's `h.<name>` is snake_case and never names them.
"""
import os
import re
import sys

ROOT = sys.argv[1]
OUT = sys.argv[2]


def strip(s):
    s = re.sub(r'"(\\.|[^"\\\n])*"', '""', s)
    s = re.sub(r"'(\\.|[^'\\\n])'", "' '", s)
    s = re.sub(r'//[^\n]*', '', s)
    s = re.sub(r'/\*.*?\*/', '', s, flags=re.S)
    return s


def split_top(s):
    out, d, cur = [], 0, ''
    for c in s:
        if c in '<([{':
            d += 1
        if c in '>)]}':
            d -= 1
        if c == ',' and d == 0:
            out.append(cur)
            cur = ''
        else:
            cur += c
    out.append(cur)
    return out


SIG = re.compile(r'^((?:\[[^\]]*\]\s*)*)((?:(?:public|private|internal|protected|override|virtual|abstract|sealed|new|static|unsafe|extern)\s+)*)'
                 r'([\w.]+(?:<.*?>)?(?:\[\])?\??|\([^)]*\)(?:\[\])?)\s+(\w+)\s*\((.*)\)\s*(=>.*)?$', re.S)


def parse_file(path, classes):
    src = strip(open(path, encoding='utf-8').read())
    depth = 0
    stack = []
    start = 0
    cur = None
    for m in re.finditer(r'[{};]', src):
        ch = m.group(0)
        chunk = src[start:m.start()]
        if ch == '{':
            cm = re.search(r'\bclass\s+(\w+)(?:\s*:\s*(\w+))?', chunk)
            if cm and depth == 0:
                cur = cm.group(1)
                classes[cur] = {'base': cm.group(2), 'methods': [], 'abstract': bool(re.search(r'\babstract\b', chunk))}
            if depth == 1 and cur:
                method(chunk, classes[cur])
            stack.append(ch)
            depth += 1
            start = m.end()
            continue
        if ch == '}':
            depth -= 1
            stack.pop()
            start = m.end()
            continue
        if depth == 1 and cur:
            method(chunk, classes[cur])
        start = m.end()


def method(chunk, cls):
    st = chunk.strip()
    # an expression body may hold braces: cut at the arrow
    head = st.split('=>')[0].strip()
    mm = SIG.match(head)
    if not mm:
        return
    mods = mm.group(2).split()
    typ, name, params = mm.group(3), mm.group(4), mm.group(5)
    if 'public' not in mods or 'static' in mods or typ == 'void':
        return
    if typ in ('class', 'struct', 'record', 'new', 'return'):
        return
    ps = [p.strip() for p in split_top(params) if p.strip()]
    if all('=' in p for p in ps):
        cls['methods'].append(name)


classes = {}
for d, _, files in os.walk(os.path.join(ROOT, 'Sim')):
    for f in sorted(files):
        if f.endswith('.cs'):
            parse_file(os.path.join(d, f), classes)


def all_methods(c):
    names = []
    while c in classes:
        names += classes[c]['methods']
        c = classes[c]['base']
    return sorted(set(names))


def is_hazard(c):
    b = classes[c]['base']
    while b:
        if b == 'Hazard':
            return True
        b = classes.get(b, {}).get('base')
    return False


types = ['SimState', 'RoomRuntime'] + sorted((c for c in classes if is_hazard(c) and not classes[c]['abstract']), key=lambda s: s.encode())
lines = [
    '//! GENERATED by gen/cs_methods.py from the C# sim (tools/fastsim/Sim): the state types of C#',
    '//! `Visibility.state_types()` (SimState, RoomRuntime, then every non-abstract Hazard subclass by',
    '//! name) and the no-argument methods `Visibility.no_arg_method` finds on each by reflection',
    '//! (public, inherited too, not void, every parameter optional; Object\'s own left out).',
    '//! Regenerate when a sim type gains or loses such a method (see gen/cs_methods.py).',
    '',
    '/// (class, its no-argument methods in ordinal order), in `state_types()` order.',
    'pub const STATE_TYPES: &[(&str, &[&str])] = &[',
]
for t in types:
    ms = ', '.join('"%s"' % m for m in all_methods(t))
    lines.append('    ("%s", &[%s]),' % (t, ms))
lines.append('];')
open(OUT, 'w', newline='\n').write('\n'.join(lines) + '\n')
for t in types:
    print(t + ': ' + ' '.join(all_methods(t)))
